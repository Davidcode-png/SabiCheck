import uuid
from datetime import datetime

from pydantic import (
    BaseModel,
    ConfigDict,
    EmailStr,
    Field,
    field_validator,
    model_validator,
)

from src.domain.models.organization import (
    Industry,
    OrganizationRole,
    RegistrationType,
)
from src.domain.schemas.attachment import FileAttachmentRead


class OrganizationBase(BaseModel):
    model_config = ConfigDict(from_attributes=True, str_strip_whitespace=True)

    name: str = Field(min_length=1, max_length=255)
    registration_type: RegistrationType
    registration_code: str = Field(min_length=1, max_length=255)
    industry_type: Industry
    website: str | None = Field(default=None, max_length=255)
    state: str = Field(min_length=1, max_length=255)
    country: str = Field(default="Nigeria", min_length=1, max_length=255)
    address: str = Field(min_length=1, max_length=512)
    contact_person_full_name: str = Field(min_length=1, max_length=255)
    business_email: EmailStr
    phone_no: str = Field(min_length=7, max_length=32)
    registration_details: str | None = Field(default=None, max_length=5000)
    manufacturer_prefix: str = Field(
        default="ORG",
        min_length=3,
        max_length=3,
        pattern=r"^[A-Za-z0-9]{3}$",
        description="Three-character prefix used at the start of verification codes",
    )

    @field_validator("manufacturer_prefix")
    @classmethod
    def normalize_manufacturer_prefix(cls, value: str) -> str:
        return value.upper()


class OrganizationCreate(OrganizationBase):
    # Generated by the API when omitted.
    reference_number: str | None = Field(default=None, max_length=64)


class OrganizationUpdate(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    name: str | None = Field(default=None, min_length=1, max_length=255)
    registration_type: RegistrationType | None = None
    registration_code: str | None = Field(
        default=None, min_length=1, max_length=255
    )
    industry_type: Industry | None = None
    website: str | None = Field(default=None, max_length=255)
    state: str | None = Field(default=None, min_length=1, max_length=255)
    country: str | None = Field(default=None, min_length=1, max_length=255)
    address: str | None = Field(default=None, min_length=1, max_length=512)
    contact_person_full_name: str | None = Field(
        default=None, min_length=1, max_length=255
    )
    business_email: EmailStr | None = None
    phone_no: str | None = Field(default=None, min_length=7, max_length=32)
    registration_details: str | None = Field(default=None, max_length=5000)
    manufacturer_prefix: str | None = Field(
        default=None,
        min_length=3,
        max_length=3,
        pattern=r"^[A-Za-z0-9]{3}$",
    )

    @field_validator("manufacturer_prefix")
    @classmethod
    def normalize_manufacturer_prefix(cls, value: str | None) -> str | None:
        return value.upper() if value else value

    @model_validator(mode="after")
    def reject_null_required_fields(self) -> "OrganizationUpdate":
        """Only the optional columns can be cleared with an explicit null."""
        optional_fields = {"website", "registration_details"}
        invalid = [
            field
            for field in self.model_fields_set - optional_fields
            if getattr(self, field) is None
        ]
        if invalid:
            raise ValueError(f"{', '.join(sorted(invalid))} cannot be null")
        return self


class OrganizationRead(OrganizationBase):
    id: uuid.UUID
    reference_number: str
    role: OrganizationRole
    created_at: datetime
    updated_at: datetime
    attachments: list[FileAttachmentRead] = Field(default_factory=list)


class OrganizationMemberRead(BaseModel):
    id: uuid.UUID
    user_id: uuid.UUID
    full_name: str
    email: str
    role: OrganizationRole
    joined_at: datetime
